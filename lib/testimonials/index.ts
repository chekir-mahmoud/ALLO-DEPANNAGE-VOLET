/**
 * Récupère les témoignages pour un service et un département spécifiques
 * Cherche d'abord par service, puis filtre par département si disponible
 */
export function getTestimonialsByServiceAndDepartment(
  serviceSlug: string,
  departmentSlug?: string,
): Testimonial[] {
  const serviceTestimonials = getTestimonialsByService(serviceSlug)

  // Si des témoignages de service existent, les retourner en priorité
  if (serviceTestimonials.length > 0) {
    return serviceTestimonials
  }

  // Fallback sur les témoignages du département
  return getTestimonialsByDepartment(departmentSlug || "gironde")
}

/**
 * Remplace dynamiquement les villes des témoignages par les villes du département
 * Distribue les villes du département sur les témoignages de façon cyclique
 */
export function replaceTestimonialCitiesWithDepartmentCities(
  testimonials: Testimonial[],
  departmentCities: Record<string, { name: string }> | undefined,
): Testimonial[] {
  if (!departmentCities || Object.keys(departmentCities).length === 0) {
    return testimonials
  }

  const cityArray = Object.values(departmentCities).map((city) => city.name)

  return testimonials.map((testimonial, index) => ({
    ...testimonial,
    location: cityArray[index % cityArray.length],
  }))
}

